private fun chapter(
    number: Int,
    title: String,
    paragraphs: List<String>,
): ReadableChapter =
    ReadableChapter(
        id = "chapter-$number",
        title = title,
        paragraphs =
            paragraphs.mapIndexed { index, text ->
                ReadableParagraph(
                    id = "chapter-$number-paragraph-${index + 1}",
                    text = text,
                )
            },
    )
